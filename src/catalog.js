const sampleNote = (title, category) =>
  category === "stay"
    ? "Chọn chỗ nghỉ phù hợp và lưu địa chỉ của bạn tại đây."
    : category === "move"
      ? "Chừa thời gian cho quãng đường về và chọn phương tiện phù hợp."
      : title.includes("sáng")
        ? "Một bữa sáng không vội, tự chọn quán trên đường."
        : category === "food"
          ? "Nghỉ chân, ăn ngon và dành thời gian trò chuyện."
          : category === "other"
            ? "Giữ lại một khoảng trống cho điều bạn tình cờ thích."
            : "";
const activity = (
  id,
  day,
  start,
  title,
  category,
  duration,
  cost,
  extra = {},
) => ({
  id,
  placeId: "",
  day,
  title,
  category,
  start,
  duration,
  cost,
  costMode: "person",
  notes: sampleNote(title, category),
  done: false,
  ...extra,
});
const visit = (id, placeId, day, start) => {
  const place = places.find((entry) => entry.id === placeId);
  return activity(
    id,
    day,
    start,
    place.name,
    place.category,
    place.duration,
    place.cost,
    { placeId, costMode: place.costMode },
  );
};

